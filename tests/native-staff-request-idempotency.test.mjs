import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {SagaOpsLocalPostgresRuntime} from '../src/db/local-postgres-runtime.mjs';
import {SAGA_POS_DURABLE_PILOT_IDS as ids,SagaPosPostgresRepository} from '../src/db/saga-pos-postgres-repository.mjs';
import {createNativeStaffService} from '../src/services/native-staff.mjs';

test('request attempts survive lost responses, concurrent replay, review and actor isolation without duplicate rows',async t=>{
 const dataDir=await mkdtemp(join(tmpdir(),'sagapos-request-attempt-'));
 let runtime=new SagaOpsLocalPostgresRuntime({dataDir});await runtime.start();t.after(async()=>{await runtime.close();await rm(dataDir,{recursive:true,force:true});});
 for(const file of ['native-staff-schema.sql','native-staff-roster-v2.sql','native-staff-report-v3.sql','native-staff-payroll-v4.sql'])await runtime.db.exec(await readFile(new URL(`../ops/production/${file}`,import.meta.url),'utf8'));
 await new SagaPosPostgresRepository({db:runtime.db}).seedPilotContext();
 await runtime.query("select set_config('app.current_user_id',$1,false)",[ids.authUserId]);await runtime.db.exec('set role "sagaops-production"');
 const service=createNativeStaffService({db:runtime.db,ids});
 const first=await service.createAccount({name:'Fixture One',role:'barista'}),second=await service.createAccount({name:'Fixture Two',role:'barista'});
 const actor=first.account.id,key=randomUUID(),payload={idempotencyKey:key,category:'permission',reason:'Fixture permission request',startAt:'2026-10-02T01:00:00Z',endAt:'2026-10-02T02:00:00Z'};
 assert.equal((await service.requestOperationStatus(actor,key)).status,'NOT_FOUND');
 const results=await Promise.all(Array.from({length:6},()=>service.submitRequest(actor,payload)));
 assert.equal(new Set(results.map(r=>r.id)).size,1);assert.equal(results.filter(r=>!r.replayed).length,1);
 const lookup=await service.requestOperationStatus(actor,key);assert.equal(lookup.status,'COMMITTED');assert.equal(lookup.request.id,results[0].id);
 await assert.rejects(service.submitRequest(actor,{...payload,reason:'Changed request intent'}),{code:'request_idempotency_conflict'});
 assert.equal((await service.requestOperationStatus(second.account.id,key)).status,'NOT_FOUND');
 const anotherOutlet=createNativeStaffService({db:runtime.db,ids:{...ids,outletId:randomUUID()}});
 assert.equal((await anotherOutlet.requestOperationStatus(actor,key)).status,'NOT_FOUND');
 await assert.rejects(anotherOutlet.submitRequest(actor,payload),{code:'staff_not_found'});
 const anotherTenant=createNativeStaffService({db:runtime.db,ids:{...ids,organizationId:randomUUID()}});
 assert.equal((await anotherTenant.requestOperationStatus(actor,key)).status,'NOT_FOUND');
 await assert.rejects(anotherTenant.submitRequest(actor,payload),{code:'staff_not_found'});
 const other=await service.submitRequest(second.account.id,payload);assert.notEqual(other.id,results[0].id);
 const next=await service.submitRequest(actor,{...payload,idempotencyKey:randomUUID()});assert.notEqual(next.id,results[0].id);
 await service.reviewRequest(results[0].id,'approved','Fixture approval');
 assert.equal((await service.submitRequest(actor,payload)).state,'approved');
 const invalidKey=randomUUID();await assert.rejects(service.submitRequest(actor,{...payload,idempotencyKey:invalidKey,category:'shift_swap',targetStaffId:second.account.id,targetScheduleId:randomUUID()}));
 assert.equal((await service.requestOperationStatus(actor,invalidKey)).status,'NOT_FOUND');
 await assert.rejects(service.requestOperationStatus(actor,'bad-key'),{code:'request_idempotency_key_invalid'});
 const count=(await runtime.query('select count(*)::integer as count from sagaops.native_staff_requests')).rows[0].count;assert.equal(count,3);
 await runtime.close();runtime=new SagaOpsLocalPostgresRuntime({dataDir});await runtime.start();
 await runtime.query("select set_config('app.current_user_id',$1,false)",[ids.authUserId]);await runtime.db.exec('set role "sagaops-production"');
 const restored=createNativeStaffService({db:runtime.db,ids});
 assert.equal((await restored.requestOperationStatus(actor,key)).request.id,results[0].id);
 assert.equal((await restored.submitRequest(actor,payload)).id,results[0].id);
 assert.equal((await runtime.query('select count(*)::integer as count from sagaops.native_staff_requests')).rows[0].count,3);
});
